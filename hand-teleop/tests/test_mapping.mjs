import assert from 'node:assert/strict';
import {degreesToRaw,rawToDegrees,validatePose} from '../web/mapping.mjs';
const c={points:[{degrees:0,raw:1000},{degrees:30,raw:700},{degrees:90,raw:0}]};
assert.equal(degreesToRaw(c,30),700);
assert.equal(degreesToRaw(c,60),350);
assert.equal(rawToDegrees(c,350),60);
assert.equal(rawToDegrees(c,1000),0);
assert.throws(()=>degreesToRaw(c,91));
assert.throws(()=>rawToDegrees(c,-1));
assert.throws(()=>rawToDegrees(c,NaN));
const opposite={points:[{degrees:0,raw:0},{degrees:75,raw:1000}]};
assert.equal(degreesToRaw(opposite,37.5),500);
assert.equal(rawToDegrees(opposite,500),37.5);
const pose={schema:1,side:'R',raw:[0,1,2,3,4,5],mapping_sha256:'abc'};
assert.deepEqual(validatePose(pose,'abc').raw,pose.raw);
assert.throws(()=>validatePose(pose,'different'));
assert.throws(()=>validatePose({...pose,raw:[true,1,2,3,4,5]},'abc'));
assert.throws(()=>validatePose({...pose,side:'B'},'abc'));
console.log('Mapping and pose validation: passed');
