import assert from 'node:assert/strict';
import fs from 'node:fs';
import {displayedPose,displayAngleScale,visualReference} from '../web/visual-reference.mjs';
import {degreesToRaw,rawToDegrees} from '../web/mapping.mjs';
const mapping=JSON.parse(fs.readFileSync(new URL('../calibration.example.json',import.meta.url)));
const original=JSON.stringify(mapping);
for(const side of ['L','R']) {
  const raw=[...visualReference[side].raw],saved=[...raw];
  const pose=displayedPose(mapping,side,raw);
  assert.ok(Math.abs(pose.angles[4])===0,'photographed thumb is straight at its own reference');
  assert.ok(Math.abs(pose.angles[5])===0,'photographed thumb rotation defines only a display origin');
  assert.equal(pose.thumbRestYaw,0);
  assert.ok(pose.thumbBase[0]<-.495,'thumb lies beside, not inside the palm');
  assert.deepEqual(raw,saved,'display correction must never rewrite register values');
  for(let i=0;i<4;i++)assert.equal(pose.angles[i],rawToDegrees(mapping.hands[side].channels[i],raw[i]));
  for(let i=0;i<6;i++)assert.equal(degreesToRaw(mapping.hands[side].channels[i],rawToDegrees(mapping.hands[side].channels[i],raw[i])),raw[i]);
  raw[4]=Math.min(1000,raw[4]+100);
  const changed=displayedPose(mapping,side,raw);
  assert.equal(changed.angles[4]-pose.angles[4],-(rawToDegrees(mapping.hands[side].channels[4],raw[4])-rawToDegrees(mapping.hands[side].channels[4],saved[4])),'only the thumb drawing reverses toward the palm');
  assert.ok(changed.angles[4]>0,'positive X rotation bends +Y thumb toward palm +Z');
  assert.equal(changed.angles[5],pose.angles[5],'thumb rotation is unchanged');
  const oldAngle=rawToDegrees(mapping.hands[side].channels[4],saved[4]);
  const dragged=degreesToRaw(mapping.hands[side].channels[4],oldAngle+3*displayAngleScale(mapping,side,4));
  const dragRaw=[...saved];dragRaw[4]=dragged;
  assert.ok(displayedPose(mapping,side,dragRaw).angles[4]>pose.angles[4],'downward mouse gesture bends the drawing toward the palm');
  for(let i=0;i<6;i++)assert.equal(displayAngleScale(mapping,side,i),i>=4?-1:1);
  assert.deepEqual(pose.thumbRotationAxis,[0,0,1],'thumb base sweeps in the palm plane, not around its own length');
  const spreadRaw=[...saved];spreadRaw[5]=0;
  const spread=displayedPose(mapping,side,spreadRaw);
  assert.ok(spread.angles[5]>70,'low rotation raw produces lateral thumb spread');
  const theta=spread.angles[5]*Math.PI/180;
  const localTip=[-Math.sin(theta),Math.cos(theta),0];
  assert.ok(localTip[0]<-.9&&localTip[1]>0,'right-hand thumb spreads outward along negative X');
  assert.ok(-localTip[0]>.9,'left-hand mirror spreads outward along positive X');
  const parallelRaw=[...saved];parallelRaw[5]=1000;
  assert.ok(Math.abs(displayedPose(mapping,side,parallelRaw).angles[5])<1.1,'high rotation raw aligns thumb with forward +Y fingers');
  assert.equal(spread.angles[4],pose.angles[4],'rotation edits do not change flexion');
}
assert.equal(JSON.stringify(mapping),original,'calibration mapping remains unchanged');
mapping.hands.L.verified=true;
assert.equal(displayAngleScale(mapping,'L',4),1,'verified field mapping supersedes the display sign');
const calibrated=displayedPose(mapping,'L',visualReference.L.raw);
assert.equal(calibrated.referenceApplied,false,'a verified mapping supersedes the display-only anchor');
assert.deepEqual(calibrated.thumbBase,mapping.model.thumb_base);
assert.deepEqual(calibrated.thumbRotationAxis,mapping.model.thumb_rotation_axis);
console.log('Visual reference correction and unchanged raw values: passed');
