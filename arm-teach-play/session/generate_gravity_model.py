"""Extract pinned G1 arm inertials and RH56DFTP equivalent loads; no device I/O."""
import hashlib
import json
import math
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT=Path(__file__).resolve().parent
SOURCE=ROOT.parents[1]/'arm-button/reference/g1_29dof_rev_1_0_with_inspire_hand_FTP.urdf'
EXPECTED='63097d7366e1903b595c6adbdb187b205f5c1b1189088ca5aea32d25622415cb'
PARTS=('shoulder_pitch','shoulder_roll','shoulder_yaw','elbow','wrist_roll','wrist_pitch','wrist_yaw')

def vec(value):return [float(x) for x in value.split()]
def add(a,b):return [x+y for x,y in zip(a,b)]
def mv(a,b):return [sum(a[i][j]*b[j] for j in range(3)) for i in range(3)]
def mm(a,b):return [[sum(a[i][k]*b[k][j] for k in range(3)) for j in range(3)] for i in range(3)]
def rpy(v):
    r,p,y=v;cr,sr,cp,sp,cy,sy=math.cos(r),math.sin(r),math.cos(p),math.sin(p),math.cos(y),math.sin(y)
    return [[cy*cp,cy*sp*sr-sy*cr,cy*sp*cr+sy*sr],[sy*cp,sy*sp*sr+cy*cr,sy*sp*cr-cy*sr],[-sp,cp*sr,cp*cr]]
def origin(element):
    e=element.find('origin')
    return (vec(e.get('xyz','0 0 0')),vec(e.get('rpy','0 0 0'))) if e is not None else ([0.]*3,[0.]*3)

def extract():
    assert hashlib.sha256(SOURCE.read_bytes()).hexdigest()==EXPECTED,'official_model_hash_mismatch'
    robot=ET.parse(SOURCE).getroot();links={e.get('name'):e for e in robot.findall('link')}
    joints={e.get('name'):e for e in robot.findall('joint')};children={}
    for j in joints.values():children.setdefault(j.find('parent').get('link'),[]).append(j)
    arms=[];loads=[]
    for side in ('left','right'):
        chain=[]
        for part in PARTS:
            j=joints[side+'_'+part+'_joint'];i=links[j.find('child').get('link')].find('inertial')
            xyz,angles=origin(j)
            chain.append({'xyz':xyz,'rpy':angles,'axis':vec(j.find('axis').get('xyz')),
                          'mass':float(i.find('mass').get('value')),'com':origin(i)[0],
                          'effort':float(j.find('limit').get('effort'))})
        # Lump all hand bodies at their URDF zero finger posture, in wrist-yaw frame.
        # This replaces the rubber hand; it is not added on top of it.
        points=[]
        def walk(name,rotation,position):
            for j in children.get(name,[]):
                xyz,angles=origin(j);child=j.find('child').get('link')
                p=add(position,mv(rotation,xyz));R=mm(rotation,rpy(angles));i=links[child].find('inertial')
                if i is not None:points.append((float(i.find('mass').get('value')),add(p,mv(R,origin(i)[0]))))
                walk(child,R,p)
        walk(side+'_wrist_yaw_link',rpy([0,0,0]),[0.]*3)
        mass=sum(m for m,p in points);com=[sum(m*p[k] for m,p in points)/mass for k in range(3)]
        loads.append({'side':side,'model':'RH56DFTP','mass_kg':mass,'com_in_wrist_yaw_m':com,
                      'finger_posture':'URDF zero (nominal open), not live finger tracking',
                      'extra_mass_kg':0,'bodies':len(points)})
        arms.append(chain)
    waist=[]
    for part in ('yaw','roll','pitch'):
        j=joints['waist_'+part+'_joint'];xyz,angles=origin(j)
        waist.append({'xyz':xyz,'rpy':angles,'axis':vec(j.find('axis').get('xyz'))})
    return {'schema':1,'source_sha256':EXPECTED,'source_commit':'5994d4faef0a9cadd3287f8de0199a67eeb2a259',
            'robot':'G1 29DoF','hands_confirmed_by_user':'both RH56DFTP, no extra load',
            'imu_frame':'pelvis; LowState quaternion wxyz','waist':waist,'arms':arms,'loads':loads,
            'ff_limit_nm':[[.6*j['effort'] for j in arm] for arm in arms],
            'ff_slew_nm_s':[20.,20.,20.,20.,20.,5.,5.],'ramp_s':2.}

def literal(v):
    return '{'+','.join(literal(x) for x in v)+'}' if isinstance(v,list) else format(v,'.17g')

def generate():
    data=extract();digest=hashlib.sha256(json.dumps(data,sort_keys=True,separators=(',',':')).encode()).hexdigest()
    data['model_sha256']=digest
    text='// Generated by generate_gravity_model.py from pinned official URDF.\n#pragma once\nnamespace gravity {\n'
    text+='inline constexpr const char* MODEL_SHA256="'+digest+'";\n'
    for side,arm in zip(('LEFT','RIGHT'),data['arms']):
        text+='inline const std::array<Joint,7> '+side+'={{\n'
        for j in arm:text+='  {'+','.join(literal(j[k]) for k in ('xyz','rpy','axis','mass','com'))+'},\n'
        text+='}};\n'
    text+='inline const std::array<Joint,3> WAIST={{\n'
    for j in data['waist']:text+='  {'+','.join([literal(j[k]) for k in ('xyz','rpy','axis')]+['0','{0,0,0}'])+'},\n'
    text+='}};\n'
    text+='inline const std::array<Load,2> LOADS={{'+','.join('{'+literal(l['mass_kg'])+','+literal(l['com_in_wrist_yaw_m'])+'}' for l in data['loads'])+'}};\n'
    text+='inline const std::array<double,14> FF_LIMIT='+literal(sum(data['ff_limit_nm'],[]))+';\n'
    text+='inline const std::array<double,7> FF_SLEW='+literal(data['ff_slew_nm_s'])+';\n}\n'
    (ROOT/'gravity_model.generated.hpp').write_text(text,encoding='utf-8')
    (ROOT/'gravity_model.json').write_text(json.dumps(data,indent=2),encoding='utf-8')
    return data

if __name__=='__main__':
    data=generate();print(json.dumps({'model_sha256':data['model_sha256'],'loads':data['loads']}))
